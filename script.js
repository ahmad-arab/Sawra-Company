const rtlLanguages = new Set(["ar", "ku"]);
let activeLanguage = localStorage.getItem("sawra-language") || "en";

function applyLanguage(language) {
  const dictionary = translations[language] || translations.en;
  activeLanguage = language;

  document.documentElement.lang = language;
  document.documentElement.dir = rtlLanguages.has(language) ? "rtl" : "ltr";
  document.body.classList.toggle("rtl", rtlLanguages.has(language));

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key]) {
      element.textContent = dictionary[key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    if (dictionary[key]) {
      element.placeholder = dictionary[key];
    }
  });

  document.querySelectorAll("[data-lang]").forEach((button) => {
    const isActive = button.dataset.lang === language;
    button.classList.toggle("active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  localStorage.setItem("sawra-language", language);
}

function initLanguageSwitch() {
  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.addEventListener("click", () => applyLanguage(button.dataset.lang));
  });

  applyLanguage(activeLanguage);
}

function initBootstrapFallbacks() {
  if (window.bootstrap) {
    return;
  }

  const collapse = document.querySelector("#sawraNavbar");
  const toggler = document.querySelector("[data-bs-target=\"#sawraNavbar\"]");

  if (collapse && toggler) {
    toggler.addEventListener("click", () => {
      const isOpen = collapse.classList.toggle("show");
      toggler.setAttribute("aria-expanded", String(isOpen));
    });
  }

  document.querySelectorAll("[data-bs-toggle=\"pill\"]").forEach((button) => {
    button.addEventListener("click", () => {
      const target = document.querySelector(button.dataset.bsTarget);

      document.querySelectorAll("[data-bs-toggle=\"pill\"]").forEach((item) => {
        item.classList.toggle("active", item === button);
        item.setAttribute("aria-selected", String(item === button));
      });

      document.querySelectorAll(".tab-pane").forEach((pane) => {
        const isTarget = pane === target;
        pane.classList.toggle("active", isTarget);
        pane.classList.toggle("show", isTarget);
      });
    });
  });

  const carousel = document.getElementById("heroCarousel");
  if (carousel) {
    const slides = Array.from(carousel.querySelectorAll(".carousel-item"));
    const indicators = Array.from(carousel.querySelectorAll(".hero-indicators button"));
    let activeIndex = Math.max(0, slides.findIndex((slide) => slide.classList.contains("active")));

    const showSlide = (index) => {
      activeIndex = (index + slides.length) % slides.length;
      slides.forEach((slide, slideIndex) => slide.classList.toggle("active", slideIndex === activeIndex));
      indicators.forEach((indicator, indicatorIndex) => {
        const isActive = indicatorIndex === activeIndex;
        indicator.classList.toggle("active", isActive);
        indicator.toggleAttribute("aria-current", isActive);
      });
      carousel.dispatchEvent(new CustomEvent("slide.bs.carousel"));
    };

    indicators.forEach((indicator, index) => {
      indicator.addEventListener("click", () => showSlide(index));
    });

    window.setInterval(() => showSlide(activeIndex + 1), 6800);
  }

  window.bootstrap = {
    Collapse: {
      getOrCreateInstance: (element) => ({
        hide: () => {
          element.classList.remove("show");
          if (toggler) {
            toggler.setAttribute("aria-expanded", "false");
          }
        }
      })
    }
  };
}

function initNavbar() {
  const navbar = document.querySelector(".sawra-nav");
  const links = document.querySelectorAll(".nav-link");
  const collapse = document.querySelector(".navbar-collapse");

  const updateNav = () => {
    navbar.classList.toggle("nav-scrolled", window.scrollY > 24);
  };

  links.forEach((link) => {
    link.addEventListener("click", () => {
      if (collapse && collapse.classList.contains("show")) {
        bootstrap.Collapse.getOrCreateInstance(collapse).hide();
      }
    });
  });

  updateNav();
  window.addEventListener("scroll", updateNav, { passive: true });
}

function initCounters() {
  const counters = document.querySelectorAll(".counter");

  const animateCounter = (counter) => {
    const target = Number(counter.dataset.target || 0);
    const duration = 1200;
    const started = performance.now();

    const tick = (now) => {
      const progress = Math.min((now - started) / duration, 1);
      const eased = 1 - Math.pow(1 - progress, 3);
      counter.textContent = Math.round(target * eased).toLocaleString(activeLanguage);

      if (progress < 1) {
        requestAnimationFrame(tick);
      }
    };

    requestAnimationFrame(tick);
  };

  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting && !entry.target.dataset.counted) {
        entry.target.dataset.counted = "true";
        animateCounter(entry.target);
      }
    });
  }, { threshold: 0.35 });

  counters.forEach((counter) => observer.observe(counter));
}

function initFilters() {
  const buttons = document.querySelectorAll("[data-filter]");
  const cards = document.querySelectorAll(".product-card");

  buttons.forEach((button) => {
    button.addEventListener("click", () => {
      const filter = button.dataset.filter;

      buttons.forEach((item) => item.classList.toggle("active", item === button));
      cards.forEach((card) => {
        const shouldShow = filter === "all" || card.dataset.category === filter;
        card.classList.toggle("is-hidden", !shouldShow);
      });
    });
  });
}

function initCarouselProgress() {
  const carousel = document.getElementById("heroCarousel");
  const progress = document.querySelector(".carousel-progress span");

  if (!carousel || !progress) {
    return;
  }

  carousel.addEventListener("slide.bs.carousel", () => {
    progress.style.animation = "none";
    progress.offsetHeight;
    progress.style.animation = "";
  });
}

function initContactForm() {
  const form = document.getElementById("quoteForm");
  const status = document.getElementById("formStatus");

  if (!form || !status) {
    return;
  }

  form.addEventListener("submit", (event) => {
    event.preventDefault();
    status.textContent = translations[activeLanguage].formSuccess;
    form.reset();
  });
}

document.addEventListener("DOMContentLoaded", () => {
  initLanguageSwitch();
  initBootstrapFallbacks();
  initNavbar();
  initCounters();
  initFilters();
  initCarouselProgress();
  initContactForm();

  if (window.lucide) {
    window.lucide.createIcons();
  }
});
